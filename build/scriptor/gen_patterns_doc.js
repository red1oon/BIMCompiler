L.push('**A save is part of a transaction.** One action of a user can write many records. A Complete on a sales order, for example, writes the shipment, its lines, the invoice and the accounting entries together. They form one *transaction*: either all of them are kept (commit) or, if anything fails near the end — a closed period, say — all of them are undone (rollback), as if they never existed.');
L.push('');
L.push('**Legacy iDempiere announces a save early.** Its \"after save\" notices (`postCreate`, `postUpdate`) are sent the moment each record is saved, while the transaction is still open (`PO.java:2799-2804`), and they are delivered a little later on another thread. If the transaction is then rolled back, a notice has already gone out about a record that never existed, and a listener reading the database may not find a record it was told about. Legacy also has a separate after-commit hook (`Trx.addTrxEventListener` → `afterCommit`, `Trx.java:452,761`) that careful code can use; the standard notices do not use it.');
L.push('');
L.push('**The twin announces a save once, after the commit.** In the SQLite twin one user action becomes one *op group*, and the kernel commits the whole group in one step. Observing listeners are told after that step succeeded — exactly once, in a fixed order, and never for a group that was rolled back. The screens and messages are the same as legacy; only this behind-the-scenes moment is defined more strictly.');
L.push('');
L.push('**Why replication needs exactly that.** Sending a team member\'s changes to the others is such an observing listener. If it could see a save that was later undone, it would send a ghost document to the whole team — a second source of truth. Told only after the commit, it can only ever send what really happened.');
L.push('');
L.push('**A received record is saved as a replica, and that is a different event.** When a device takes in a record from another device, it saves it as a *replica* (legacy `po.saveReplica(true)`), and the save raises its own events — *after new replication*, *after change replication*, *before delete replication* — instead of the ordinary *after new* / *after change* / *before delete* (`PO.java:2785-2787, 4300`). A process chain that must run where the declaration ARRIVES — head office turning a station\'s sale lines into one completed order with Import Orders (pattern P1) — listens to *after new replication*. The station\'s own save of its sale lines raises only the ordinary *after new*, so the chain never runs at the station: one document, one Complete, at head office only.');
