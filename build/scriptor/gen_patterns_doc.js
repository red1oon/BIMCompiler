function describe(m) {
  var t = m.virtual ? 'the declaration of `' + m.virtual + '`' : 'the row "' + m.row + '"', out = [];
  Object.keys(m.set || {}).forEach(function (k) { out.push('set `' + k + '` to `' + JSON.stringify(m.set[k]) + '`'); });
  (m.unset || []).forEach(function (k) { out.push('remove `' + k + '`'); });
  if (m.setColumn) out.push('change the column `' + m.setColumn.name + '` so that `cls` is `' + m.setColumn.cls + '`');
  if (m.addColumn) out.push('add a second column `' + m.addColumn.name + '`');
  return 'In ' + t + ': ' + out.join('; ') + '.';
}
