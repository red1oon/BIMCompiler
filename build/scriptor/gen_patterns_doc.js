L.push('## 8. Principles behind this design — for anyone building something similar');
L.push('');
L.push('*Distilled 2026-10-27 from the team-layer work (`prompts/TEAMWORK_FRAMEWORK.md` §38, `prompts/TEAM_REPLICATION_PLUGIN_STUDY.md` §8–§10). Each one is a rule this project already enforces, not a wish.*');
L.push('');
L.push('1. **Twin before you innovate.** Copy the legacy mechanism exactly; a difference found by running both side by side is fixed on the new side. Users see no change, so adopting it costs them nothing.');
L.push('2. **Every server rule becomes signed data.** One completer per document, who may use which document action, which keys are trusted, which translation rules apply — each is an owner-signed policy inside the shared log, judged the same way by every device. No referee in the middle.');
L.push('3. **Declare where the action happens, derive in one place.** A point of sale only declares its lines; one processor completes once and returns what is needed. Mistakes show up as consequences (under-declaring starves your own replenishment), not as online checks.');
L.push('4. **Send the minimum.** Ids, references, quantities and codes. Every device already holds the master data, so meaning never travels.');
L.push('5. **Separate by permission, not by promise.** A plugin is given only the hooks its job needs. The team layer may observe saves and store what it receives; it is structurally unable to complete, post or number a document.');
L.push('6. **Rows over code.** Flows, listeners and access are dictionary rows, never per-window code; progress is counted as X of N over the whole dictionary, never one hand-picked demo.');
