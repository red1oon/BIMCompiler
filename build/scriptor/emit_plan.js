// emit_plan.js — compile flow rows and write the plan a browser adapter loads (prompts/TEAMWORK_FRAMEWORK.md §24). Deterministic: same rows -> same bytes.
// Unsigned prototype (the plan-signing key is §16.13 Q1). Usage: node build/scriptor/emit_plan.js <rows.json> <out.js>
'use strict';
var path = require('path'), fs = require('fs'), crypto = require('crypto');
function emit(db, rows, srcName) {
  var COMPILE = require('./compile.js'), r = COMPILE.compile(db, rows, {});
  if (r.virtualErrors.length) throw new Error('virtual table errors: ' + r.virtualErrors.join(' | '));
  var bad = r.plan.filter(function (f) { return f.error || (f.treatmentErrors || []).length; });
  if (bad.length) throw new Error('flow errors: ' + bad.map(function (f) { return f.name + ' ' + (f.error || f.treatmentErrors.join(',')); }).join(' | '));
  var flows = r.plan.map(function (f) {
    return { name: f.name, table: f.table, dir: f.dir, audience: (rows.filter(function (x) { return x.name === f.name; })[0] || {}).audience || 'hub', implicit: f.implicit || [],
      payload: f.payload.map(function (p) { var o = { col: p.col, cls: p.cls }; if (p.values) o.values = p.values; return o; }) };
  });
  var plan = { v: 1, hash: r.hash, flows: flows };
  return '// GENERATED by bim-compiler build/scriptor/emit_plan.js from ' + srcName + ' — DO NOT EDIT (prompts/TEAMWORK_FRAMEWORK.md §24). Plan sha256 ' + r.hash + '. Unsigned prototype.\n' +
    '(function (g) { g.TEAM_PLAN = ' + JSON.stringify(plan) + '; })(typeof window !== \'undefined\' ? window : globalThis);\n';
}
module.exports = { emit: emit };
if (require.main === module) {
  var Better = require('better-sqlite3'), db = new Better(path.join(__dirname, '..', 'erp', 'ad_full.db'), { readonly: true });
  var src = process.argv[2], out = process.argv[3];
  fs.writeFileSync(out, emit(db, JSON.parse(fs.readFileSync(src, 'utf8')), path.basename(src)));
  console.log('§PLAN_EMIT ' + out + ' sha256=' + crypto.createHash('sha256').update(fs.readFileSync(out)).digest('hex').slice(0, 12));
}
