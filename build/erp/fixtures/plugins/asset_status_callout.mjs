// asset_status_callout.mjs — the "behaviour" teaching sample for Ninja Create (NINJA_MODE_PILL.md ponder,
// ERPGuide §Create). The dumb-simplest worked example a user crafts by hand:
//
//   ONE column rule on a one-table window — set Description to 'Ready' when IsActive is On, 'Starting' when Off.
//
// This is the BEHAVIOUR half of a .foldbundle. The STRUCTURE half (the ACME_Asset table/menu/window, and the
// crucial line `AD_Column.Callout = 'com.acme.AssetCallout.statusFromActive'` on the IsActive column) is
// generated by Emit from the model sheet — that callout NAME on the column is the ONE wiring seam that ties the
// generated structure to this hand-crafted JS. Together (structure + this) = one file that replaces
// 2Pack(structure) + JAR(behaviour) + classpath + restart, installing live.
//
// Faithful clone of fixtures/plugins/widget_callout.mjs (C-1) — same ad_callout.registerHandler seam, no new
// abstraction. A callout DERIVES (returns derived:{col:val}); it does NOT validate (that is ad_valrule).
export const manifest = {
  id: 'com.acme.asset-status',
  version: '1.0.0',
  engineVersion: '>=0.10.0',
  requires: {},
  contributions: { callout: { module: 'self', tables: ['ACME_Asset'] } }
};

// Must match AD_Column.Callout on the IsActive column (the structure half sets this; see the §-seam above).
const HANDLER = 'com.acme.AssetCallout.statusFromActive';

export async function activate(ctx) {
  // Register into the SAME ad_callout REGISTRY the engine already dispatches through.
  ctx.callout.registerHandler(HANDLER, function (c, info) {
    var r = info.record || {};
    var on = (r.IsActive != null ? r.IsActive : r.isactive) === 'Y';   // case-insensitive, like the engine handlers
    return { derived: { Description: on ? 'Ready' : 'Starting' } };
  });
}

export async function deactivate(ctx) {
  if (ctx.callout && ctx.callout.REGISTRY) delete ctx.callout.REGISTRY[HANDLER];
}
