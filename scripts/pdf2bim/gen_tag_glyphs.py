#!/usr/bin/env python3 -I
# Implements prompts/PDF2BIM_VECTOR_PROBE.md §36 — writes the type's tag glyph samples, once, from a sheet whose printed areas are known (the dictionary's hindsight read). Only cells that segment into exactly their string give samples. Deterministic.
# Usage: gen_tag_glyphs.py <p1.svg> <rosetta.json> <template.json> <pdf> <out.json>
import sys,json,os,collections
sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)))
import type_template as TT
svg,rj,tj,pdf,out=sys.argv[1:6]; R=json.load(open(rj)); T=TT.load(tj); K=R['sheet']['mm_per_pt_fitted']; P=TT.stroked_paths(svg); log=lambda *a:print('§GLY',*a,flush=True)
B=TT.room_tags(P,T,K); xa,y5=TT.plan_origin(pdf,R,T); A,stray=TT.assign_tags(B,R,xa,y5,K)
if stray or any(len(v)!=1 for v in A.values()): log('WRONG the tags do not fill the preset cells',{k:len(v) for k,v in A.items()},'stray',len(stray)); sys.exit(1)
S=collections.defaultdict(list)
for r in R['rooms']:
    b=A[r['name']][0]
    for cell,st in ((TT.area_cell(b),'%.2fsqm'%r['printed_sqm']),((b['x0'],b['xm'],b['y0'],(b['y0']+b['y1'])/2),r.get('ffl_from_agl'))):   # the FFL cell is the same pen and hand: it holds the sheet's only clean 0s (§36)
        if not st: continue
        ink=sorted(TT.cell_ink(P,cell,T,K)); g=[];cur=[ink[0]]
        for p in ink[1:]:
            if p[0]-cur[-1][0]>.13*K: g.append(cur);cur=[p]
            else: cur.append(p)
        g.append(cur); g=[q for q in g if q[-1][0]-q[0][0]>0]
        log(r['name'],st,'segments',len(g),'used' if len(g)==len(st) else 'not clean, no samples')
        if len(g)!=len(st): continue
        for ch,q in zip(st,g):
            x_=q[0][0]; S[ch].append(dict(tag=r['name'],pts=sorted({(round(a-x_,1),round(b_,1)) for a,b_ in q})[::2]))
O={'_readme':"§36: tag glyph samples for type 'Low cost single storey unit', in mm from the glyph's left and the cell's top. Generated by gen_tag_glyphs.py. A preset marking to compare with, not a font. Add samples for another drafter's set.",'samples':{}}
for ch in sorted(S):
    keep=[];seen=set()
    for s in S[ch]:   # at most 4, different tags first, so a tag left out still leaves samples
        if s['tag'] not in seen: seen.add(s['tag']); keep.append(s)
    for s in S[ch]:
        if len(keep)>=4: break
        if s not in keep: keep.append(s)
    O['samples'][ch]=keep[:4]
json.dump(O,open(out,'w',encoding='utf-8'),separators=(',',':')); log('RESULT chars',''.join(sorted(S)),'samples',{k:len(v) for k,v in O['samples'].items()},'tags per char',{k:len({s['tag'] for s in v}) for k,v in O['samples'].items()},'wrote',out)
